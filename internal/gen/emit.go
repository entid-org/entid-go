// Generate emits the Go source of an engine implementing the bundle.
//
// The output is deterministic: the same bundle always produces the same bytes,
// so a regeneration shows in a diff exactly which rule changed.
func Generate(b *Bundle, pkg string) ([]byte, error) {
	g := &generator{bundle: b, names: newNaming(b), pkg: pkg}
	if err := g.run(); err != nil {
		return nil, err
	}
	src, err := format.Source(g.buf.Bytes())
	if err != nil {
		// A syntax error in generated code is a bug in the generator, and the
		// unformatted source is what makes it findable.
		return nil, fmt.Errorf("the generated source does not parse: %w\n%s", err, g.buf.String())
	}
	return src, nil
}

type generator struct {
	bundle *Bundle
	names  *naming
	pkg    string
	buf    bytes.Buffer
}

func (g *generator) p(format string, args ...any) {
	fmt.Fprintf(&g.buf, format, args...)
	g.buf.WriteByte('\n')
}

func (g *generator) run() error {
	g.emitHeader()
	g.emitMetadata()
	g.emitDefinitions()
	g.emitDispatch()
	if err := g.emitCanonicalizers(); err != nil {
		return err
	}
	g.emitFormats()
	g.emitChecksums()
	g.emitTables()
	return nil
}

func (g *generator) emitHeader() {
	b := g.bundle
	g.p("// Copyright The LibBusinessID Authors.")
	g.p("// SPDX-License-Identifier: Apache-2.0")
	g.p("")
	g.p("// Code generated by businessid-gen from businessid-rules %s. DO NOT EDIT.", commentText(b.RulesVersion))
	g.p("//")
	g.p("// Every rule below comes from the compiled bundle the spec repository")
	g.p("// publishes. To change one, change the rule upstream and regenerate.")
	g.p("")
	g.p("package %s", g.pkg)
	g.p("")
	g.p("import rt %q", "github.com/libbusinessid/businessid-go/internal/runtime")
	g.p("")
}

// commentText renders a bundle string inside a single line comment. Section 10
// of ir.md only requires rules_version to be non empty, so it may carry a line
// break or a NUL, neither of which a Go comment survives; such a version is
// quoted rather than refused, since refusing it is not the generator's call.
func commentText(s string) string {
	for i := 0; i < len(s); i++ {
		if c := s[i]; c < 0x20 || c == 0x7f {
			return strconv.Quote(s)
		}
	}
	return s
}

func (g *generator) emitMetadata() {
	b := g.bundle
	g.p("// Identity of the bundle this engine was generated from.")
	g.p("const (")
	g.p("\trulesVersion  = %q", b.RulesVersion)
	g.p("\tformatVersion = %d", b.FormatVersion)
	g.p(")")
	g.p("")
	g.p("// requiredCapabilities lists the capability IDs the bundle needs, and")
	g.p("// supportedCapabilities those the generator implements. Both are arrays,")
	g.p("// not slices, so they live in read-only data instead of being built when")
	g.p("// the program starts.")
	g.p("var (")
	g.p("\trequiredCapabilities  = [%d]uint32{%s}", len(b.RequiredFeatureIDs), joinUint32(b.RequiredFeatureIDs))
	g.p("\tsupportedCapabilities = [%d]uint32{%s}", len(SupportedFeatures), joinUint32(SupportedFeatures))
	g.p(")")
	g.p("")

	kinds := make([]string, len(b.Dispatchers))
	for i, d := range b.Dispatchers {
		kinds[i] = d.Kind
	}
	g.p("// kinds are the canonical identifier families this engine can route.")
	g.p("var kinds = [%d]string{%s}", len(kinds), joinQuoted(kinds))
	g.p("")
}

func (g *generator) emitDefinitions() {
	b := g.bundle
	g.p("// definition identifies one identifier definition of the bundle.")
	g.p("type definition uint8")
	g.p("")
	g.p("// The definitions this engine implements.")
	g.p("const (")
	for i, d := range b.Identifiers {
		country := d.CountryCode
		if !d.HasCountryCode {
			country = "GLOBAL"
		}
		if i == 0 {
			g.p("\t%s definition = iota // %s / %s", g.names.DefConst(d.ID), d.Kind, country)
			continue
		}
		g.p("\t%s // %s / %s", g.names.DefConst(d.ID), d.Kind, country)
	}
	g.p(")")
	g.p("")

	g.p("// definitionCountry is the ISO 3166-1 alpha-2 code of a definition, empty")
	g.p("// for a global one.")
	g.p("func definitionCountry(d definition) string {")
	g.p("\tswitch d {")
	for _, d := range b.Identifiers {
		if d.HasCountryCode {
			g.p("\tcase %s:", g.names.DefConst(d.ID))
			g.p("\t\treturn %q", d.CountryCode)
		}
	}
	g.p("\t}")
	g.p("\treturn \"\"")
	g.p("}")
	g.p("")

	g.p("// definitionDefaultProfile is the profile a definition documents as its")
	g.p("// own default. Section 5.2 of ir.md applies it once the definition is")
	g.p("// selected, and only when the caller supplied no profile.")
	g.p("func definitionDefaultProfile(d definition) Profile {")
	g.p("\tswitch d {")
	for _, d := range b.Identifiers {
		g.p("\tcase %s:", g.names.DefConst(d.ID))
		g.p("\t\treturn %s", profileConst(d.DefaultProfile))
	}
	g.p("\t}")
	g.p("\treturn Compatible")
	g.p("}")
	g.p("")

	g.p("// absentChecksumReason explains why no checksum runs for a definition that")
	g.p("// publishes none.")
	g.p("func absentChecksumReason(d definition) Reason {")
	g.p("\tswitch d {")
	for _, d := range b.Identifiers {
		if d.HasAbsentChecksumReason {
			g.p("\tcase %s:", g.names.DefConst(d.ID))
			g.p("\t\treturn %s", d.AbsentChecksumReason.GoName())
		}
	}
	g.p("\t}")
	g.p("\treturn ReasonUnsupportedChecksum")
	g.p("}")
	g.p("")

	g.emitCoverage()
}

func (g *generator) emitCoverage() {
	b := g.bundle
	g.p("// coverageTable describes every definition the bundle carries, with its")
	g.p("// provenance. It is built on demand: introspection is never a hot path.")
	g.p("func coverageTable() []Coverage {")
	g.p("\treturn []Coverage{")
	for _, d := range b.Identifiers {
		g.p("\t\t{")
		g.p("\t\t\tKind: %q,", d.Kind)
		if d.HasCountryCode {
			g.p("\t\t\tCountryCode: %q,", d.CountryCode)
		}
		g.p("\t\t\tHasChecksum: %t,", d.HasChecksumProgram)
		if d.HasAbsentChecksumReason {
			g.p("\t\t\tAbsentChecksumReason: %s,", d.AbsentChecksumReason.GoName())
		}
		g.p("\t\t\tDefaultProfile: %s,", profileConst(d.DefaultProfile))
		if len(d.Sources) > 0 {
			g.p("\t\t\tSources: []Source{")
			for _, s := range d.Sources {
				g.p("\t\t\t\t{")
				g.p("\t\t\t\t\tID: %q,", s.ID)
				g.p("\t\t\t\t\tURL: %q,", s.URL)
				g.p("\t\t\t\t\tAuthority: %q,", s.Authority)
				g.p("\t\t\t\t\tTitle: %q,", s.Title)
				g.p("\t\t\t\t\tAccessedAt: %q,", s.AccessedAt)
				g.p("\t\t\t\t\tJurisdiction: %q,", s.Jurisdiction)
				g.p("\t\t\t\t\tLanguage: %q,", s.Language)
				g.p("\t\t\t\t\tNotes: %q,", s.Notes)
				g.p("\t\t\t\t\tLicenseOrTerms: %q,", s.LicenseOrTerms)
				if s.HasArchiveURL {
					g.p("\t\t\t\t\tArchiveURL: %q,", s.ArchiveURL)
				}
				if s.Tier != TierUnspecified {
					g.p("\t\t\t\t\tTier: %s,", tierConst(s.Tier))
				}
				g.p("\t\t\t\t},")
			}
			g.p("\t\t\t},")
		}
		g.p("\t\t},")
	}
	g.p("\t}")
	g.p("}")
	g.p("")
}

// emitDispatch generates the routing tables of section 5 of ir.md. Each one is
// a switch: nothing is built when the program starts.
func (g *generator) emitDispatch() {
	b := g.bundle

	g.p("// dispatcher identifies one kind family of the bundle.")
	g.p("type dispatcher uint8")
	g.p("")
	g.p("// The dispatchers this engine implements.")
	g.p("const (")
	g.p("\tnoDispatcher dispatcher = iota")
	for _, d := range b.Dispatchers {
		g.p("\t%s // %s", g.names.DispatcherConst(d.Kind), d.Kind)
	}
	g.p(")")
	g.p("")

	g.p("// dispatcherOf resolves a kind token, already trimmed and lower cased,")
	g.p("// through the canonical kinds and the alias space.")
	g.p("func dispatcherOf(token string) dispatcher {")
	g.p("\tswitch token {")
	for _, d := range b.Dispatchers {
		tokens := append([]string{d.Kind}, d.KindAliases...)
		quoted := make([]string, len(tokens))
		for i, t := range tokens {
			quoted[i] = strconv.Quote(t)
		}
		g.p("\tcase %s:", strings.Join(quoted, ", "))
		g.p("\t\treturn %s", g.names.DispatcherConst(d.Kind))
	}
	g.p("\t}")
	g.p("\treturn noDispatcher")
	g.p("}")
	g.p("")

	g.p("// canonicalKind is the kind a dispatcher reports, whatever alias the")
	g.p("// caller used.")
	g.p("func canonicalKind(d dispatcher) string {")
	g.p("\tswitch d {")
	for _, d := range b.Dispatchers {
		g.p("\tcase %s:", g.names.DispatcherConst(d.Kind))
		g.p("\t\treturn %q", d.Kind)
	}
	g.p("\t}")
	g.p("\treturn \"\"")
	g.p("}")
	g.p("")

	g.emitCountryAlias()
	g.emitCountryTarget()
	g.emitPrefixTarget()
	g.emitFallbackTargets()
	g.emitPreCanonicalizers()
}

func (g *generator) emitCountryAlias() {
	g.p("// countryAlias maps a normalized country token onto a canonical code. A")
	g.p("// token the dispatcher does not alias is returned unchanged.")
	g.p("func countryAlias(d dispatcher, code string) string {")
	g.p("\tswitch d {")
	for _, disp := range g.bundle.Dispatchers {
		if len(disp.CountryAliases) == 0 {
			continue
		}
		g.p("\tcase %s:", g.names.DispatcherConst(disp.Kind))
		g.p("\t\tswitch code {")
		for _, a := range disp.CountryAliases {
			g.p("\t\tcase %q:", a.Alias)
			g.p("\t\t\treturn %q", a.CountryCode)
		}
		g.p("\t\t}")
	}
	g.p("\t}")
	g.p("\treturn code")
	g.p("}")
	g.p("")
}

func (g *generator) emitCountryTarget() {
	g.p("// countryTarget resolves a canonical country code to the definition that")
	g.p("// owns it, for one dispatcher.")
	g.p("func countryTarget(d dispatcher, code string) (definition, bool) {")
	g.p("\tswitch d {")
	for _, disp := range g.bundle.Dispatchers {
		targets := countryTargets(disp)
		if len(targets) == 0 {
			continue
		}
		g.p("\tcase %s:", g.names.DispatcherConst(disp.Kind))
		g.p("\t\tswitch code {")
		for _, t := range targets {
			g.p("\t\tcase %q:", t.CountryCode)
			g.p("\t\t\treturn %s, true", g.names.DefConst(t.IdentifierDefinitionID))
		}
		g.p("\t\t}")
	}
	g.p("\t}")
	g.p("\treturn 0, false")
	g.p("}")
	g.p("")
}

func (g *generator) emitPrefixTarget() {
	g.p("// prefixTarget resolves the longest accepted prefix the pre-canonical value")
	g.p("// starts with. Prefixes are tested from the longest to the shortest, so an")
	g.p("// overlap is settled by length as section 5 requires.")
	g.p("func prefixTarget(d dispatcher, value string) (definition, bool) {")
	g.p("\tswitch d {")
	for _, disp := range g.bundle.Dispatchers {
		type entry struct {
			prefix string
			def    uint32
		}
		var entries []entry
		for _, t := range disp.Targets {
			for _, p := range t.AcceptedPrefixes {
				entries = append(entries, entry{p, t.IdentifierDefinitionID})
			}
		}
		if len(entries) == 0 {
			continue
		}
		sort.SliceStable(entries, func(i, j int) bool {
			if len(entries[i].prefix) != len(entries[j].prefix) {
				return len(entries[i].prefix) > len(entries[j].prefix)
			}
			return entries[i].prefix < entries[j].prefix
		})
		g.p("\tcase %s:", g.names.DispatcherConst(disp.Kind))
		for _, e := range entries {
			g.p("\t\tif rt.HasPrefix(value, %q) {", e.prefix)
			g.p("\t\t\treturn %s, true", g.names.DefConst(e.def))
			g.p("\t\t}")
		}
	}
	g.p("\t}")
	g.p("\treturn 0, false")
	g.p("}")
	g.p("")
}

func (g *generator) emitFallbackTargets() {
	g.p("// globalTarget is the single GLOBAL definition of a dispatcher, when it")
	g.p("// declares one. A dispatcher with a GLOBAL target has no other.")
	g.p("func globalTarget(d dispatcher) (definition, bool) {")
	g.p("\tswitch d {")
	for _, disp := range g.bundle.Dispatchers {
		if disp.Global != nil {
			g.p("\tcase %s:", g.names.DispatcherConst(disp.Kind))
			g.p("\t\treturn %s, true", g.names.DefConst(disp.Global.IdentifierDefinitionID))
		}
	}
	g.p("\t}")
	g.p("\treturn 0, false")
	g.p("}")
	g.p("")

	g.p("// unprefixedTarget is the single definition a dispatcher may select with")
	g.p("// neither a country context nor a recognized prefix.")
	g.p("func unprefixedTarget(d dispatcher) (definition, bool) {")
	g.p("\tswitch d {")
	for _, disp := range g.bundle.Dispatchers {
		if disp.Unprefixed != nil {
			g.p("\tcase %s:", g.names.DispatcherConst(disp.Kind))
			g.p("\t\treturn %s, true", g.names.DefConst(disp.Unprefixed.IdentifierDefinitionID))
		}
	}
	g.p("\t}")
	g.p("\treturn 0, false")
	g.p("}")
	g.p("")
}

// countryTargets lists the country specific targets of a dispatcher.
func countryTargets(d *IdentifierDispatcher) []*DispatchTarget {
	var out []*DispatchTarget
	for _, t := range d.Targets {
		if t.HasCountryCode {
			out = append(out, t)
		}
	}
	return out
}
